package br.com.fiap.boletimplus;

import org.springframework.beans.factory.InitializingBean;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.context.annotation.Bean;
import org.springframework.core.io.ByteArrayResource;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;

import javax.sql.DataSource;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Carrega no H2 os mesmos scripts do Oracle (docker/oracle), com a senha de demonstração 123456.
 * Única adaptação, só em memória: o H2 exige `BY DEFAULT` em `GENERATED AS IDENTITY`.
 */
@TestConfiguration
class BancoDeTeste {

    @Bean
    InitializingBean carregarScriptsDoOracle(DataSource dataSource) {
        return () -> {
            String ddl = script("docker/oracle/01_ddl.sql")
                    .replace("GENERATED AS IDENTITY", "GENERATED BY DEFAULT AS IDENTITY");
            var populator = new ResourceDatabasePopulator(recurso(ddl),
                    recurso(script("docker/oracle/02_dml.sql")),
                    recurso(script("docker/oracle/03_senhas_demo.sql")));
            populator.setSqlScriptEncoding("UTF-8");
            populator.execute(dataSource);
        };
    }

    private static ByteArrayResource recurso(String sql) {
        return new ByteArrayResource(sql.getBytes(StandardCharsets.UTF_8));
    }

    private static String script(String caminho) throws IOException {
        return Files.readString(Path.of(caminho), StandardCharsets.UTF_8);
    }
}
